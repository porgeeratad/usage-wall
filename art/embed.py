#!/usr/bin/env python3
"""Embed the chosen hero PNGs (art/hero/*.png, trimmed, binary alpha) into index.html as data URIs between the
`// BEGIN ART` / `// END ART` markers. The server only serves index.html + fonts, so the art rides inside the page.
usage: python3 art/embed.py   (then `usage-dashboard` to reload the screen)"""
import base64, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
HTML = os.path.join(HERE, "..", "web", "index.html")
art = {os.path.splitext(f)[0]: "data:image/png;base64," + base64.b64encode(open(os.path.join(HERE, "hero", f), "rb").read()).decode()
       for f in sorted(os.listdir(os.path.join(HERE, "hero"))) if f.endswith(".png")}
block = ("// BEGIN ART (generated by art/embed.py from art/hero/*.png — SpriteCook pixel art, 1 px = 1 cell)\n"
         "const ART = {\n" + "".join(f"  {k}: {json.dumps(v)},\n" for k, v in art.items()) + "};\n// END ART")
src = open(HTML, encoding="utf-8").read()
new, n = re.subn(r"// BEGIN ART.*?// END ART", lambda _: block, src, flags=re.S)
if n != 1:
    sys.exit("index.html: ART markers not found")
if new != src:
    open(HTML, "w", encoding="utf-8").write(new)
print("index.html art", "updated" if new != src else "unchanged", {k: len(v) for k, v in art.items()})
